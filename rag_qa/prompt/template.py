from langchain_core.prompts import PromptTemplate

# 提示词模板类
class RAGPrompts:
    @staticmethod
    def rag_prompt() -> PromptTemplate:
        """
        函数功能：rag模版。直接根据上下文和问题生成答案。
        :return: PromptTemplate对象，直接检索提示词模板
        """
        return PromptTemplate(
            template="""
            你是一个专业的法律专家，负责帮助用户回答问题。请按以下步骤处理：
            
            1. **分析问题、参考案例、法律依据**：
                - 基于提供的参考案例、法律依据(如果有)和你的知识回答问题。
                - 如果答案来源于搜索到的文档，请在回答中明确说明，例如：“根据提供的文档”。
            
            2. **评估对话历史**：
                - 检查对话历史是否与当前问题相关(例如，是否涉及相同的话题、实体或问题背景)。
                - 如果对话历史与问题相关，请结合历史信息生成更精准的回答。
                - 如果对话历史无关(例如，仅包含问候或不相关的内容)，忽略历史，仅基于上下文和问题回答。
                
            3. **生成回答**：
                - 提供清晰、确切的回答，避免模糊不清的表达和无关信息。
                - 如果参考案例、法律依据、历史消息均不足以回答问题，请回复：“信息不足，无法回答。”。
                - 如果对话历史、法律依据、参考案例与问题无关，直接忽略，无需强调无关等任何解释
                - 以用户问题为核心，先明确回答用户的问题，再展开分析。不要脱离用户的具体情境空泛论述。
                - 引用参考案例时，必须先简要概述该参考案例的基本案情（如当事人、争议焦点、裁判结果），字数大致在70字以内，再说明其与用户问题的关联性和参考价值。不要仅给出参考案例编号而不说明案情。引用时使用"在相关司法实践中"、"类似参考案例显示"等表述，不要使用"根据提供的参考案例"。
                - 引用法律依据时，需写明法律名称和法律编号，并说明该法律的核心内容及其对用户问题的适用性。
                - 分点论述必须使用连续递增序号：1. 2. 3. ...，严禁所有条目都编号为1。每个要点独立编号，不可重复。
                - 回答结构建议使用分段标题组织，例如用"### 收益归属"、"### 返还范围"、"### 法律依据"等标题分隔不同分析维度，每个标题下直接论述，无需编号。
                - 在回答中，不要带有人名，一律用人称代词进行替换。
                - 在生成答案时，不需要加"答案"，直接给出内容即可。
            
            以下示例仅用于学习输出格式和判断逻辑，不是当前问题，不要直接当作实际输入回答。
            
            ### 示例1：有法律依据
            对话历史：None。
            参考案例：[1] 最高人民法院指导案例XX号：出借人甲与借款人乙未约定借期内利息，乙经催告后仍逾期还款。法院认定：借款未约定利息的，借期内不支付利息；逾期还款的，出借人可主张逾期利息，按年利率6%计算，判决乙偿还本金10万元及逾期利息。
            法律依据：[1] 《民法典》第675条：借款人应当按照约定的期限返还借款。第676条：借款人未按照约定的期限返还借款的，应当按照约定或者国家有关规定支付逾期利息。
            问题：乙能否要求甲偿还本金并支付逾期利息？
            回答：
            可以。根据用户描述，乙已催告甲还款但甲未还。法律依据方面，《民法典》第675条规定借款人应按期返还借款，第676条规定逾期还款需支付逾期利息。参考案例中，最高人民法院指导案例XX号的情形与本案类似：出借人甲与借款人乙同样未约定利息，乙经催告后逾期未还，法院最终判决乙偿还本金10万元并支付逾期利息（年利率6%）。该案例的争议焦点和本案一致，即未约定利息时逾期利息能否主张。结论：乙可以要求甲偿还本金并支付逾期利息。
            
            ### 示例2：信息不足
            对话历史：None。
            参考案例：None。
            法律依据：仅提供《民法典》第188条诉讼时效依据。
            问题：戊与己签订买卖合同，己逾期交货，戊能否解除合同？
            回答：
            信息不足，无法回答。
            
            对话历史：{history}
            参考案例：{case}
            法律依据：{legal_provision}
            问题：{question}
            
            回答：
            """,
            input_variables=["history", "case", "legal_provision", "question"],
        )

    @staticmethod
    def hyde_search() -> PromptTemplate:
        """
        函数功能：假设问题检索。使用LLM生成一个假设答案，基于假设答案进行检索
        :return: PromptTemplate对象，假设问题检索提示词模板
        """
        return PromptTemplate(
            template="""
                你是一位专业的法律专家。请根据用户提出的问题，给出一段假设性的法律分析。
                要求：
                1. 使用正式的法律语言，尽量包含相关的法律名称、法条编号或法律术语。
                2. 不需要完全准确，但应体现该问题涉及的法律概念和可能的法律依据。
                3. 回答控制在2-4句话，简洁明了。
                4. 仅输出结果文本，不要换行，不要编号，不要任何解释

                问题：{query}
                假设性法律分析：
            """,
            input_variables=["query"],
        )

    @staticmethod
    def subquery_search() -> PromptTemplate:
        """
        函数功能：子查询检索。将长/复杂查询拆分为多个子查询，便于分布检索
        :return: PromptTemplate对象，子查询检索提示词模板
        """
        return PromptTemplate(
            template="""
                你是一位专业的法律专家。请根据用户的提问，将复杂问题拆分为多个可独立检索简单子问题。
                要求：
                1. 每个子问题应语义完整、可独立理解，不依赖原问题的上下文。
                2. 子问题应覆盖原问题涉及到的不同法律维度(如构成要件、法律后果、使用条件等)。
                3. 使用正式的法律语言，保留关键法律术语。
                4. 拆分2~3个子问题，每行一个，不要编号。
                5. 每个子问题独占一行，不要编号，不要空行，不要任何解释。
                
                问题：{query}
                子问题：
            """,
            input_variables=["query"],
        )
    
    @staticmethod
    def recall_search() -> PromptTemplate:
        """
        函数功能：回溯查询。将复杂/冗余查询简化为简单问题，提升检索关键词的集中性
        :return: PromptTemplate对象，回溯查询提示词模板
        """
        return PromptTemplate(
            template="""
                你是一位专业的法律专家。请将用户的复杂问题简化为一个简单的问题：
                要求：
                1. 取出口语化表达、冗余修饰和无关信息，保留核心法律事实和问题。
                2. 使用正式的法律术语替换日常用语(如"离婚分房子" -> "离婚时夫妻共同财产分割规则")
                3. 改写后的问题应为依据完整的疑问句，可直接用于法律检索
                4. 仅输出改写后的问题，不要换行，不要编号，不要任何解释。
                
                问题：{query}
                改写后的问题：
            """,
            input_variables=["query"],
        )

    @staticmethod
    def classification_prompt():
        """
        函数功能：检索分类。将用户问题进行分类，查看问题属于哪一种检索类型
        :return: PromptTemplate对象，检索分类提示词模板
        """
        return PromptTemplate(
            template="""
                你是一名分类专家。请判断用户问题最适合一下哪种检索方式，仅返回一个标签。
                四种检索方式及其适用场景：
                    - direct：问题简洁明确，法律术语清晰，可直接检索。如"离婚冷静期是多久？""诉讼时效是几年？"
                    - hyde：问题涉及具体情境分析，需要用假设性答案辅助检索。如"甲借给乙10万没打欠条，乙能要回来吗？"
                    - subquery：问题包含多个法律维度，需要拆分才能全面检索。如"婚前贷款买房婚后共同还贷，离婚时如何分割？"
                    - recall：问题口语化、冗长或包含大量无关信息，需要简化后检索。如"我在公司干了好几年了老板一直不跟我签合同现在把我开了怎么办？"  
                
                要求：
                1. 仅返回一个标签：direct、hyde、subquery、recall 之一。
                2. 不要返回任何解释或额外内容。
                3. 如果无法明确判断，默认返回 direct。
                4. 返回内容不允许有空格、换行符等其他字符。
                
                ### 示例1：
                问题：AI 学科学费是多少？
                分类结果：direct
                
                ### 示例2：
                问题：人工智能在教育领域的应用有哪些？
                分类结果：hyde
                
                ### 示例3：
                问题：比较 Milvus 和 Zilliz Cloud 的优缺点。
                分类结果：subquery
                
                ### 示例4：
                问题：我有一个包含 100 亿条记录的数据集，想把它存储到 Milvus 中进行查询。可以吗？
                分类结果：recall
                
                问题：{query}
                分类结果：
            """,
            input_variables=["query"]
        )

    @staticmethod
    def general_prompt() -> PromptTemplate:
        """
        函数功能：通用问答提示词模板。用于非法律问题，不检索知识库，直接由 LLM 回答。
        :return: PromptTemplate对象，通用问答提示词模板
        """
        return PromptTemplate(
            template="""
            你是一个友好、简洁的LawChain智能小助手，负责回答日常问题。
            
            要求：
            1. 直接回答用户问题，简洁准确，不要长篇大论
            2. 不知道或者不确定的，明确说不知道，不要编写。
            3. 如果问题涉及到法律、法规、诉讼、合同、劳动、婚姻、继承、侵犯、刑事等法律领域，不要尝试回答，只回复：[这属于专业法律问题，建议咨询专业律师或使用法律咨询功能]
            4. 不要输出与问题无关的免责声明或客套话
            5. 如果问题涉及到日常打招呼，回复类似引导型内容，例如：[你好，我是LawChain智能小助手，有什么需要我的帮助吗？]
            6. 如果涉及到用途，你要给予3~4个问题，去引导用户询问法律相关的问题，引导问题要偏日常，最常见的，例如：[我可以帮你查询法律相关的问题，你可以问我：1.xxx\n2.xxx...]
            7. 在回答中，不要带有人名，一律用人称代词进行替换。
            8. 检查对话历史是否与当前问题相关(例如，是否涉及相同的话题、实体或问题背景)。
                - 如果对话历史与问题相关，请结合历史信息生成更精准的回答。
                - 如果对话历史无关(例如，仅包含问候或不相关的内容)，忽略历史，仅基于上下文和问题回答。
            
            历史记录：{history}
            问题：{query}
            回答：
            """,
            input_variables=["history", "query"]
        )

    @staticmethod
    def resolve_prompt() -> PromptTemplate:
        """
        函数功能：指代消解。结合对话历史，把省略式追问改写成自包含的完整问题。
        :return: PromptTemplate对象，指代消解提示词模板
        """
        return PromptTemplate(
            template="""
                你是对话理解助手。请结合【对话历史】，把用户的【当前问题】改写成一个
                不依赖上下文、可以独立理解的完整问题。

                要求：
                1. 把当前问题里的指代词替换成历史中的具体内容，例如：
                   "那他不给呢" → "房东一直不退押金，我该怎么办"
                   "这个能退吗" → "我买的这件商品能不能退货"
                   "还有别的办法吗" → "除了起诉，押金不退还有什么解决办法"
                2. **只输出一个问题**，不要拆分成多个子问题，不要编号。
                3. 保持用户的原始意图，不要添加用户没提到的条件或事实。
                4. 如果当前问题本身已经完整（不需要依赖历史就能理解），原样返回。
                5. 【重要】绝对不要向用户提问、不要反问、不要要求用户补充信息，不要输出"请问""您能具体说明""请提供更多信息"之类的内容。你的任务是改写问题，不是和用户对话。
                6. 如果历史信息不足以判断指代内容，就把当前问题【原样返回】，不要自行编造，也不要反问。
                7. 不要输出任何解释、前后缀说明或标点以外的内容。
                8. 输出的问题要简洁、明了，避免冗长

                ### 示例1
                对话历史：
                用户：租房押金不退怎么办
                助手：可以要求房东返还押金，协商不成可以起诉。
                当前问题：那他不给呢
                改写结果：房东一直不退押金，我该怎么办

                ### 示例2
                对话历史：
                用户：今天天气怎么样
                助手：今天晴，气温 20 到 28 度。
                当前问题：那明天呢
                改写结果：明天天气怎么样

                ### 示例3
                对话历史：
                用户：离婚冷静期是多久
                助手：离婚冷静期为三十日。
                当前问题：那诉讼离婚要多久
                改写结果：那诉讼离婚要多久

                对话历史：
                {history}
                当前问题：{question}
                改写结果：
                """,
            input_variables=["history", "question"],
        )

    @staticmethod
    def insufficient_answer(phone: str) -> str:
        """
        函数功能：检索未获得可用上下文时的兜底文案 (不经过LLM直接返回)
        :param phone: 客服电话
        :return: 提示文案
        """
        return f"信息不足，无法回答。\n如有问题请联系人工客服，电话：{phone}"

    @staticmethod
    def system_error_answer(phone: str) -> str:
        """
        函数功能：系统/LLM 异常时的兜底文案 (不经过 LLM，直接返回)
        :param phone: 客服电话
        :return: 提示文案
        """
        return f"抱歉，系统出现问题。如有疑问，请联系人工客服，电话：{phone}"

    @staticmethod
    def disclaimer(phone: str) -> str:
        """
        函数功能：统一的免责声明后缀
        :param phone: 客服电话
        :return: 提示文案
        """
        return f"\n\n上述回答仅供参考。如有疑问，请联系人工客服，电话：{phone}"
        

