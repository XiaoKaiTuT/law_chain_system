def load_manual_samples() -> list[dict]:
    """
    函数功能：把手工样本转成与 dataset_builder 一致的字段格式

    :return: [{qa_id, original_question, eval_question, ground_truth,
               answer_chars, rewrite_attempts, scene, source}, ...]
    """
    samples = []
    for item in MANUAL_SAMPLES:
        samples.append({
            "qa_id": item["manual_id"],
            # 手工样本本身就是口语化提问，不经过改写：
            #   original_question 与 eval_question 相同，rewrite_attempts=0
            "original_question": item["question"],
            "eval_question": item["question"],
            "ground_truth": item["answer"],
            "answer_chars": len(item["answer"]),
            "rewrite_attempts": 0,
            "scene": "manual",
            "source": "手工构造",
            "basis": item["basis"],
        })
    return samples


